                pcem_key[c] = (uint8_t)(rawinputkey[c] > 0 ? 1 : 0);
    }

    internal static void keyboard_process()
    {
        int c;
        int d;
        scancode[] scancodes = (AT != 0 || romset == ROM_XI8088) ? at_scancodes : scancode_xt;
        if (keyboard_scan == 0)
                return;
        if (TANDY != 0)
                scancodes = scancode_tandy;

        for (c = 0; c < 272; c++)
        {
                if (pcem_key[c] != 0)
                        keydelay[c]++;
                else
                        keydelay[c] = 0;
        }

        for (c = 0; c < 272; c++)
        {
                if (pcem_key[c] != oldkey[c])
                {
                        oldkey[c] = pcem_key[c];
                        if (pcem_key[c] != 0 && scancodes[c].scancodes_make[0] == 0)
                                continue;
                        if (pcem_key[c] == 0 && scancodes[c].scancodes_break[0] == 0)
                                continue;
                        d = 0;
                        if (pcem_key[c] != 0)
                        {
                                while (scancodes[c].scancodes_make[d] != 0)
                                        keyboard_send(scancodes[c].scancodes_make[d++]);
                        }
                        else
                        {
                                while (scancodes[c].scancodes_break[d] != 0)
                                        keyboard_send(scancodes[c].scancodes_break[d++]);
                        }
                }
        }

        for (c = 0; c < 272; c++)
        {
                if (keydelay[c] >= 30)
                {
                        keydelay[c] -= 10;
                        if (scancodes[c].scancodes_make[0] == 0)
                                continue;

                        d = 0;

                        while (scancodes[c].scancodes_make[d] != 0)
                                keyboard_send(scancodes[c].scancodes_make[d++]);
                }
        }
    }

    // pcem: keyboard.c:1472-1486
    internal static void keyboard_send_scancode(int code, int is_break)
    {
        scancode[] scancodes = (AT != 0 || romset == ROM_XI8088) ? at_scancodes : scancode_xt;
        int d = 0;

        if (keyboard_scan == 0)
                return;

        if (is_break == 0)
        {
                while (scancodes[code].scancodes_make[d] != 0)
                        keyboard_send(scancodes[code].scancodes_make[d++]);
        }
        else
        {
                while (scancodes[code].scancodes_break[d] != 0)
                        keyboard_send(scancodes[code].scancodes_break[d++]);
        }
    }
