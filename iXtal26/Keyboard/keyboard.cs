internal sealed class scancode
{
    internal uint8_t[] scancodes_make = new uint8_t[8];
    internal uint8_t[] scancodes_break = new uint8_t[8];

    internal scancode(uint8_t[] mk, uint8_t[] bk)
    {
        Array.Copy(mk, scancodes_make, mk.Length);
        Array.Copy(bk, scancodes_break, bk.Length);
    }
}

